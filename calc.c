/* Parser (recursive descent, evaluates while parsing)                      */
/* ------------------------------------------------------------------------ */

// Grammar, one function per precedence level, lowest precedence first:
//   expr    := term  { ('+' | '-') term }
//   term    := power { ('*' | '/') power }
//   power   := primary [ '**' power ]
//   primary := NUMBER | '(' expr ')'
// Precedence comes from the nesting: expr can only combine whole terms, and a
// term only whole powers, so in 3 + 2 * 5 the "2 * 5" is finished inside
// term() before expr() ever sees the '+'. The { } loops in expr and term fold
// the result into the left operand on every step, which makes + - * / left
// associative: 7 - 2 - 1 is (7 - 2) - 1.
//
// All functions return 1 on success and 0 on the first error; err_pos then
// holds the position and every caller just passes the 0 up, so the first
// error is the one reported.

static int parse_expr(Parser *p, Value *out);

// A primary must start with a number or '('. Anything else here is exactly
// the "missing operand" / "two operators in a row" / invalid character case,
// and the token we are looking at is the one to blame: the second operator,
// the bad character, a ')' as in "2 * ()", or the end of line for "3 *".
static int parse_primary(Parser *p, Value *out) {
    if (p->tok.type == T_NUM) {
        *out = p->tok.val;
        next_token(p);
        return 1;
    }
    if (p->tok.type == T_LPAREN) {
        next_token(p);
        if (!parse_expr(p, out))
            return 0;
        // A missing ')' is noticed at whatever comes instead, normally the
        // end of line, which is where rule 5 wants it reported.
        if (p->tok.type != T_RPAREN)
            return fail(p, p->tok.pos);
        next_token(p);
        return 1;
    }
    return fail(p, p->tok.pos);
}

// power := primary [ '**' power ] is right recursive, which is what makes **
// right-associative: in 2 ** 3 ** 2 the exponent of the first '**' is the
// whole rest "3 ** 2", so it is 2 ** 9 = 512.
//
// Instead of literally calling itself, this function collects the operands of
// a chain a ** b ** c ** ... into a stack and then folds them from the right.
// The result is identical to the recursive version (the rightmost '**' is
// evaluated first), but a multi-megabyte line of "2 ** 2 ** ..." cannot
// overflow the C call stack. The stack is shared: a nested chain inside
// parentheses pushes above our part and pops back to its own base before we
// continue, so we only touch entries from `base` upward.
static int parse_power(Parser *p, Value *out) {
    size_t base = p->pw_len;
    for (;;) {
        size_t start = p->tok.pos;
        Value v;
        if (!parse_primary(p, &v)) {
            p->pw_len = base;
            return 0;
        }
        if (p->pw_len == p->pw_cap) {
            p->pw_cap = p->pw_cap ? p->pw_cap * 2 : 64;
            p->pw = xrealloc(p->pw, p->pw_cap * sizeof *p->pw);
        }
        p->pw[p->pw_len].v = v;
        p->pw[p->pw_len].start = start;
        p->pw[p->pw_len].op_pos = 0;
        p->pw_len++;
        if (p->tok.type != T_POW)
            break;
        p->pw[p->pw_len - 1].op_pos = p->tok.pos;
        next_token(p);
    }

    // Fold right to left. The exponent of item i is everything to its right,
    // and that subexpression starts where item i + 1 starts, which is the
    // position reported for a negative exponent ("2 ** (1 - 2)" -> the '(').
    Value acc = p->pw[p->pw_len - 1].v;
    for (size_t i = p->pw_len - 1; i-- > base;) {
        if (!apply_pow(p, p->pw[i].v, acc, p->pw[i].op_pos, p->pw[i + 1].start, &acc)) {
            p->pw_len = base;
            return 0;
        }
    }
    p->pw_len = base;
    *out = acc;
    return 1;
}

static int parse_term(Parser *p, Value *out) {
    Value left;
    if (!parse_power(p, &left))
        return 0;
    while (p->tok.type == T_STAR || p->tok.type == T_SLASH) {
        TokType op = p->tok.type;
        size_t op_pos = p->tok.pos;
        next_token(p);
        size_t rhs_pos = p->tok.pos;
        Value right;
        if (!parse_power(p, &right))
            return 0;
        if (!apply_binary(p, op, left, right, op_pos, rhs_pos, &left))
            return 0;
    }
    *out = left;
    return 1;
}

static int parse_expr(Parser *p, Value *out) {
    Value left;
    if (!parse_term(p, &left))
        return 0;
    while (p->tok.type == T_PLUS || p->tok.type == T_MINUS) {
        TokType op = p->tok.type;
        size_t op_pos = p->tok.pos;
        next_token(p);
        size_t rhs_pos = p->tok.pos;
        Value right;
        if (!parse_term(p, &right))
            return 0;
        if (!apply_binary(p, op, left, right, op_pos, rhs_pos, &left))
            return 0;
    }
    *out = left;
    return 1;
}

