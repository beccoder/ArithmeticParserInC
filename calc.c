/* Command line                                                             */
/* ------------------------------------------------------------------------ */

static void usage(void) {
    fprintf(stderr,
            "usage: calc [-d DIR | --dir DIR] [-o OUTDIR | --output-dir OUTDIR] [input.txt]\n"
            "  calc -o OUTDIR input.txt   evaluate one file\n"
            "  calc -d DIR -o OUTDIR      evaluate every *.txt directly inside DIR\n");
}

int main(int argc, char **argv) {
    const char *dir = NULL;
    const char *out_dir = NULL;
    const char *input = NULL;

    for (int i = 1; i < argc; i++) {
        const char *a = argv[i];
        if (strcmp(a, "-d") == 0 || strcmp(a, "--dir") == 0) {
            if (i + 1 >= argc) {
                fprintf(stderr, "calc: option '%s' needs a folder\n", a);
                usage();
                return 2;
            }
            dir = argv[++i];
        } else if (strcmp(a, "-o") == 0 || strcmp(a, "--output-dir") == 0) {
            if (i + 1 >= argc) {
                fprintf(stderr, "calc: option '%s' needs a folder\n", a);
                usage();
                return 2;
            }
            out_dir = argv[++i];
        } else if (a[0] == '-' && a[1] != '\0') {
            fprintf(stderr, "calc: unknown option '%s'\n", a);
            usage();
            return 2;
        } else if (input != NULL) {
            fprintf(stderr, "calc: only one input file can be given\n");
            usage();
            return 2;
        } else {
            input = a;
        }
    }

    if (dir == NULL && input == NULL) {
        usage();
        return 2;
    }
    if (dir != NULL && input != NULL) {
        fprintf(stderr, "calc: give either -d DIR or an input file, not both\n");
        usage();
        return 2;
    }

    // Without -o the folder is <input_base>_<name>_<studentid> in the current
    // folder, where <input_base> is the file name without .txt or the -d
    // folder's own name.
    char *default_out = NULL;
    if (out_dir == NULL) {
        char *base = dir ? base_name(dir, 0) : base_name(input, 1);
        default_out = join3(base, "_" STUDENT_NAME "_", STUDENT_ID);
        free(base);
        out_dir = default_out;
    }

    int rc = dir ? process_dir(dir, out_dir) : process_file(input, out_dir);
    free(default_out);
    return rc;
}
