/* ------------------------------------------------------------------------ */
/* Growable byte buffer                                                     */
/* ------------------------------------------------------------------------ */

// Input files can be several megabytes and every result must be held back
// until the whole file is known to be error-free (rule 3: on error only
// ERROR:<pos> is written). Both the input and the output therefore live in
// buffers whose capacity doubles when full: each byte is copied O(1) times on
// average, instead of re-copying the whole buffer on every append.
typedef struct {
    char *data;
    size_t len;
    size_t cap;
} Buf;

static void *xrealloc(void *ptr, size_t size) {
    void *p = realloc(ptr, size);
    if (p == NULL) {
        fprintf(stderr, "calc: out of memory\n");
        exit(1);
    }
    return p;
}

static void buf_reserve(Buf *b, size_t extra) {
    if (b->len + extra <= b->cap)
        return;
    size_t cap = b->cap ? b->cap : 4096;
    while (cap < b->len + extra)
        cap *= 2;
    b->data = xrealloc(b->data, cap);
    b->cap = cap;
}

static void buf_append(Buf *b, const char *s, size_t n) {
    buf_reserve(b, n);
    memcpy(b->data + b->len, s, n);
    b->len += n;
}

