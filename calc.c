static int fail(Parser *p, size_t pos) {
    p->err_pos = pos;
    return 0;
}

// Applies + - * / to two values.
// op_pos  is where the operator is: a float result that is inf or NaN is
//         blamed on the operator, because the operands themselves were fine.
// rhs_pos is where the right operand starts: division by zero is blamed on
//         the right operand, because that is the value that is wrong.
static int apply_binary(Parser *p, TokType op, Value a, Value b,
                        size_t op_pos, size_t rhs_pos, Value *out) {
    if (!a.is_float && !b.is_float) {
        // Integer path. +, - and * go through unsigned so that a (never
        // tested) overflow wraps instead of being undefined behaviour.
        unsigned long long x = (unsigned long long)a.i;
        unsigned long long y = (unsigned long long)b.i;
        out->is_float = 0;
        out->f = 0.0;
        switch (op) {
        case T_PLUS:  out->i = (long long)(x + y); break;
        case T_MINUS: out->i = (long long)(x - y); break;
        case T_STAR:  out->i = (long long)(x * y); break;
        default:  // T_SLASH
            if (b.i == 0)
                return fail(p, rhs_pos);
            // LLONG_MIN / -1 does not fit and traps on x86; wrap it instead.
            // Otherwise C's '/' already truncates toward zero as required.
            out->i = (a.i == LLONG_MIN && b.i == -1) ? LLONG_MIN : a.i / b.i;
            break;
        }
        return 1;
    }

    // Float path: at least one operand is a float, so both become double.
    double x = as_double(a);
    double y = as_double(b);
    double r;
    switch (op) {
    case T_PLUS:  r = x + y; break;
    case T_MINUS: r = x - y; break;
    case T_STAR:  r = x * y; break;
    default:  // T_SLASH
        // 1.5 / 0.0 would give inf, but the rules call it division by zero,
        // so this is checked before the inf/NaN test below.
        if (y == 0.0)
            return fail(p, rhs_pos);
        r = x / y;
        break;
    }
    if (!isfinite(r))
        return fail(p, op_pos);
    out->is_float = 1;
    out->i = 0;
    out->f = r;
    return 1;
}

// base ** exp. A negative integer exponent is only an error when both sides
// are integers (the result would not be an integer); with a float base the
// spec allows it: 0.5 ** (0 - 1) is 2.
static int apply_pow(Parser *p, Value base, Value exp,
                     size_t op_pos, size_t exp_pos, Value *out) {
    if (!base.is_float && !exp.is_float) {
        if (exp.i < 0)
            return fail(p, exp_pos);
        // Exponentiation by squaring: O(log exp) multiplications, so even a
        // huge exponent is fast. x ** 0 leaves result at 1, including 0 ** 0.
        unsigned long long result = 1;
        unsigned long long b = (unsigned long long)base.i;
        unsigned long long e = (unsigned long long)exp.i;
        while (e) {
            if (e & 1u)
                result *= b;
            b *= b;
            e >>= 1;
        }
        out->is_float = 0;
        out->i = (long long)result;
        out->f = 0.0;
        return 1;
    }

    // pow() returns NaN for a negative base with a fractional exponent
    // ((0 - 8) ** 0.5) and inf on overflow (10.0 ** 400); both are blamed on
    // the '**' operator.
    double r = pow(as_double(base), as_double(exp));
    if (!isfinite(r))
        return fail(p, op_pos);
    out->is_float = 1;
    out->i = 0;
    out->f = r;
    return 1;
}

