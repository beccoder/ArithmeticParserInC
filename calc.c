// Evaluates the whole file in src[0..len) and fills `out` with the text of
// the output file: one result per expression line, or only "ERROR:<pos>".
// The scan is a single forward pass over the buffer, so the time is linear
// in the file size no matter how long the lines are.
static void evaluate(const char *src, size_t len, Buf *out) {
    Parser p;
    memset(&p, 0, sizeof p);
    p.src = src;
    p.len = len;

    int ok = 1;
    size_t i = 0;
    while (i < len) {
        size_t j = i;
        while (j < len && (src[j] == ' ' || src[j] == '\t' || src[j] == '\r'))
            j++;
        if (j >= len)
            break;
        if (src[j] == '\n') {  // blank line: no output
            i = j + 1;
            continue;
        }
        if (src[j] == '#') {  // comment line: skip it, its bytes still count
            const char *nl = memchr(src + j, '\n', len - j);
            i = nl ? (size_t)(nl - src) + 1 : len;
            continue;
        }

        p.cur = j;
        next_token(&p);
        Value v;
        if (!parse_expr(&p, &v)) {
            ok = 0;
            break;
        }
        // A complete expression must be followed by the end of the line.
        // Anything else is reported where it starts: an extra ')' as in
        // "(1 + 2))", an inline '#', or a second number as in "2 3".
        if (p.tok.type != T_EOL) {
            p.err_pos = p.tok.pos;
            ok = 0;
            break;
        }

        char tmp[64];
        int k;
        if (v.is_float)
            k = snprintf(tmp, sizeof tmp, "%.15g\n", v.f);
        else
            k = snprintf(tmp, sizeof tmp, "%lld\n", v.i);
        buf_append(out, tmp, (size_t)k);

        i = p.tok.pos + 1;  // past this line's '\n'
    }

    if (!ok) {
        // Rule 3: no partial results, only the first error.
        char tmp[64];
        int k = snprintf(tmp, sizeof tmp, "ERROR:%zu\n", p.err_pos + 1);
        out->len = 0;
        buf_append(out, tmp, (size_t)k);
    }
    free(p.pw);
}

