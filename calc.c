/* Values                                                                   */
/* ------------------------------------------------------------------------ */

// A value remembers whether it came from integer-only arithmetic. The type is
// decided purely by the literals: a literal with a '.' is a float, and an
// operation produces a float as soon as either operand is a float (rule 9).
// Otherwise everything stays in long long so that 7 / 2 truncates to 3.
typedef struct {
    int is_float;
    long long i;
    double f;
} Value;

static double as_double(Value v) {
    return v.is_float ? v.f : (double)v.i;
}

/* ------------------------------------------------------------------------ */
/* Tokenizer                                                                */
/* ------------------------------------------------------------------------ */

typedef enum {
    T_NUM,
    T_PLUS,
    T_MINUS,
    T_STAR,
    T_SLASH,
    T_POW,
    T_LPAREN,
    T_RPAREN,
    T_EOL,     // the line's '\n', or the end of the file
    T_INVALID  // any character that cannot start a token
} TokType;

// Positions are byte offsets into the whole file buffer, not into the line.
// Because the entire file is in memory and the tokenizer only ever moves a
// single index forward through it, every token's offset is already its
// position in the file; comment lines and '\n' are counted for free. The +1
// for 1-based output is applied only when ERROR:<pos> is printed.
typedef struct {
    TokType type;
    size_t pos;
    Value val;  // only for T_NUM
} Token;

// One saved operand of a ** chain, see parse_power().
typedef struct {
    Value v;
    size_t start;   // where this operand starts (error position if it is a bad exponent)
    size_t op_pos;  // where the following '**' is (error position for inf/nan)
} PowItem;

typedef struct {
    const char *src;
    size_t len;
    size_t cur;      // next unread byte
    Token tok;       // one token of lookahead
    size_t err_pos;  // 0-based offset of the first error
    PowItem *pw;     // shared stack for ** chains
    size_t pw_len;
    size_t pw_cap;
} Parser;

// strtod() would happily read "1.5e3" or hex floats, which are not valid
// here, and the file buffer is not NUL-terminated after the token. So the
// already-validated "digits.digits" text is copied out before converting it.
static double parse_double(const char *s, size_t n) {
    char small[64];
    char *tmp = n < sizeof small ? small : xrealloc(NULL, n + 1);
    memcpy(tmp, s, n);
    tmp[n] = '\0';
    double d = strtod(tmp, NULL);
    if (tmp != small)
        free(tmp);
    return d;
}

// Invalid characters are returned as a T_INVALID token instead of being
// reported here. The parser rejects them when it actually needs that token,
// so the error lands at "the token the parser was looking at", and an error
// that happens earlier (e.g. 1 / 0 &, division first) is still reported first.
static void next_token(Parser *p) {
    const char *s = p->src;
    size_t n = p->len;
    size_t i = p->cur;

    // '\r' is skipped too so files saved with Windows line endings still work.
    while (i < n && (s[i] == ' ' || s[i] == '\t' || s[i] == '\r'))
        i++;

    Token t;
    t.pos = i;
    t.val.is_float = 0;
    t.val.i = 0;
    t.val.f = 0.0;

    // The end-of-line token is not consumed: the line loop in evaluate() moves
    // past the '\n'. At the end of the file its position is the file length,
    // which prints as "file length + 1" as rule 5 asks.
    if (i >= n || s[i] == '\n') {
        t.type = T_EOL;
        p->cur = i;
        p->tok = t;
        return;
    }

    char c = s[i];
    if (isdigit((unsigned char)c)) {
        // Integers are accumulated in unsigned arithmetic: the tests never
        // overflow, but if they did, unsigned wrap-around is defined behaviour
        // and keeps the sanitizer quiet.
        size_t j = i;
        unsigned long long acc = 0;
        while (j < n && isdigit((unsigned char)s[j])) {
            acc = acc * 10u + (unsigned long long)(s[j] - '0');
            j++;
        }
        // A float needs digits on both sides of the '.'. For "5." or "5.e"
        // the number stops before the '.', which then becomes its own
        // T_INVALID token, so the error is reported at the '.' (rule 9).
        // Likewise in "1.5e3" the number is 1.5 and the 'e' is invalid.
        if (j + 1 < n && s[j] == '.' && isdigit((unsigned char)s[j + 1])) {
            j++;
            while (j < n && isdigit((unsigned char)s[j]))
                j++;
            t.val.is_float = 1;
            t.val.f = parse_double(s + i, j - i);
        } else {
            t.val.i = (long long)acc;
        }
        t.type = T_NUM;
        p->cur = j;
        p->tok = t;
        return;
    }

    size_t width = 1;
    switch (c) {
    case '+': t.type = T_PLUS; break;
    case '-': t.type = T_MINUS; break;
    case '/': t.type = T_SLASH; break;
    case '(': t.type = T_LPAREN; break;
    case ')': t.type = T_RPAREN; break;
    case '*':
        // "**" only counts when the two stars touch; "* *" is two operators
        // in a row and fails at the second one.
        if (i + 1 < n && s[i + 1] == '*') {
            t.type = T_POW;
            width = 2;
        } else {
            t.type = T_STAR;
        }
        break;
    default:  // includes '#' that is not the first non-blank of a line
        t.type = T_INVALID;
        break;
    }
    p->cur = i + width;
    p->tok = t;
}

