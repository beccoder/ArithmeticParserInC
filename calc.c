// Reads a whole file into memory. The file is read in large chunks into a
// buffer that doubles when full, so a multi-megabyte file needs only a few
// reallocations and no per-line copying. Returns NULL (errno set) on failure.
static char *read_file(const char *path, size_t *out_len) {
    struct stat st;
    if (stat(path, &st) != 0)
        return NULL;
    if (!S_ISREG(st.st_mode)) {
        errno = EISDIR;
        return NULL;
    }
    FILE *f = fopen(path, "rb");
    if (f == NULL)
        return NULL;

    size_t cap = 1 << 16;
    size_t len = 0;
    char *data = xrealloc(NULL, cap);
    for (;;) {
        if (len == cap) {
            cap *= 2;
            data = xrealloc(data, cap);
        }
        size_t got = fread(data + len, 1, cap - len, f);
        len += got;
        if (got == 0)
            break;
    }
    int bad = ferror(f);
    fclose(f);
    if (bad) {
        free(data);
        errno = EIO;
        return NULL;
    }
    *out_len = len;
    return data;
}

static char *join3(const char *a, const char *b, const char *c) {
    size_t la = strlen(a), lb = strlen(b), lc = strlen(c);
    char *s = xrealloc(NULL, la + lb + lc + 1);
    memcpy(s, a, la);
    memcpy(s + la, b, lb);
    memcpy(s + la + lb, c, lc);
    s[la + lb + lc] = '\0';
    return s;
}

// Last path component, ignoring trailing '/', optionally without ".txt".
// "labs/task1.txt" -> "task1", "../in/" -> "in".
static char *base_name(const char *path, int strip_txt) {
    size_t end = strlen(path);
    while (end > 1 && path[end - 1] == '/')
        end--;
    size_t start = end;
    while (start > 0 && path[start - 1] != '/')
        start--;
    size_t n = end - start;
    if (strip_txt && n > 4 && memcmp(path + start + n - 4, ".txt", 4) == 0)
        n -= 4;
    char *s = xrealloc(NULL, n + 1);
    memcpy(s, path + start, n);
    s[n] = '\0';
    return s;
}

static int has_txt_suffix(const char *name) {
    size_t n = strlen(name);
    return n > 4 && strcmp(name + n - 4, ".txt") == 0;
}

// Creates the output folder, or accepts it if it already exists.
static int ensure_dir(const char *path) {
    if (mkdir(path, 0777) == 0)
        return 0;
    int saved = errno;
    struct stat st;
    if (saved == EEXIST && stat(path, &st) == 0 && S_ISDIR(st.st_mode))
        return 0;
    fprintf(stderr, "calc: cannot create output folder '%s': %s\n", path, strerror(saved));
    return 1;
}

// Evaluates one input file and writes <out_dir>/<base>_<name>_<lastname>_<id>.txt.
// Returns 0 on success, 1 on an I/O problem (already reported on stderr).
static int process_file(const char *in_path, const char *out_dir) {
    size_t len = 0;
    char *src = read_file(in_path, &len);
    if (src == NULL) {
        fprintf(stderr, "calc: cannot read input file '%s': %s\n", in_path, strerror(errno));
        return 1;
    }

    Buf out = {NULL, 0, 0};
    evaluate(src, len, &out);
    free(src);

    int rc = 0;
    if (ensure_dir(out_dir) != 0) {
        rc = 1;
    } else {
        char *base = base_name(in_path, 1);
        char *dir_slash = join3(out_dir, "/", base);
        char *out_path = join3(dir_slash, "_" STUDENT_NAME "_" STUDENT_LASTNAME "_" STUDENT_ID, ".txt");
        FILE *f = fopen(out_path, "wb");
        if (f == NULL) {
            fprintf(stderr, "calc: cannot write '%s': %s\n", out_path, strerror(errno));
            rc = 1;
        } else {
            size_t written = out.len ? fwrite(out.data, 1, out.len, f) : 0;
            // fclose() can be the call that reports a failed write (disk full).
            if (fclose(f) != 0 || written != out.len) {
                fprintf(stderr, "calc: error writing '%s'\n", out_path);
                rc = 1;
            }
        }
        free(out_path);
        free(dir_slash);
        free(base);
    }
    free(out.data);
    return rc;
}

// Evaluates every regular *.txt file directly inside dir_path. Subfolders are
// never entered, and stat() filters out a folder that happens to end in .txt.
static int process_dir(const char *dir_path, const char *out_dir) {
    DIR *d = opendir(dir_path);
    if (d == NULL) {
        fprintf(stderr, "calc: cannot open input folder '%s': %s\n", dir_path, strerror(errno));
        return 1;
    }
    if (ensure_dir(out_dir) != 0) {
        closedir(d);
        return 1;
    }
    int rc = 0;
    struct dirent *e;
    while ((e = readdir(d)) != NULL) {
        // Hidden files are skipped, the same as the shell's *.txt would.
        if (e->d_name[0] == '.' || !has_txt_suffix(e->d_name))
            continue;
        char *path = join3(dir_path, "/", e->d_name);
        struct stat st;
        if (stat(path, &st) == 0 && S_ISREG(st.st_mode)) {
            if (process_file(path, out_dir) != 0)
                rc = 1;
        }
        free(path);
    }
    closedir(d);
    return rc;
}

